  let lang = 'tr';
  const listeners = [];

  function t(key, vars) {
    let s = (dict[lang] && dict[lang][key]) || dict.en[key] || key;
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
    }
    return s;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.getAttribute('data-i18n')); });
    scope.querySelectorAll('[data-i18n-html]').forEach((n) => { n.innerHTML = t(n.getAttribute('data-i18n-html')); });
    scope.querySelectorAll('[data-i18n-title]').forEach((n) => {
      const v = t(n.getAttribute('data-i18n-title'));
      n.setAttribute('title', v);
      n.setAttribute('aria-label', v);
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach((n) => { n.setAttribute('aria-label', t(n.getAttribute('data-i18n-aria'))); });
  }

  function setLanguage(l) {
    lang = l === 'en' ? 'en' : 'tr';
    document.documentElement.setAttribute('lang', lang);
    apply();
    listeners.forEach((cb) => cb(lang));
  }

  function onChange(cb) { listeners.push(cb); }
  function getLanguage() { return lang; }

  VE.i18n = { t, apply, setLanguage, onChange, getLanguage, dict };
